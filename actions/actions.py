MONTHS = (
    "januari|februari|maart|april|mei|juni|juli|augustus|september|oktober|november|december"
)
AMOUNT_RE = re.compile(r"€\s?\d{1,3}(?:\.\d{3})*(?:,\d{2})?|\b\d+,\d{2}\s?(?:euro|EUR)\b", re.I)
DATE_RE = re.compile(
    rf"\b\d{{1,2}}[-/]\d{{1,2}}[-/]\d{{2,4}}\b|\b\d{{1,2}}\s(?:{MONTHS})\s\d{{4}}\b", re.I
)


def _normalise(text: Optional[Text]) -> Text:
    text = (text or "").lower()
    text = re.sub(r"[\"'‘’“”`]", "", text)
    text = re.sub(r"[^\w\s-]", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def _all_names() -> List[Tuple[Text, Text]]:
    """(name, glossary key) pairs, longest names first."""
    pairs = [(key, key) for key in GLOSSARY]
    pairs += [(alias, key) for key, entry in GLOSSARY.items() for alias in entry["aliases"]]
    return sorted(pairs, key=lambda pair: len(pair[0]), reverse=True)


def lookup_term(term: Optional[Text]) -> Optional[Text]:
    """Return the glossary key for a term, tolerating small typos."""
    norm = _normalise(term)
    if not norm:
        return None
    names = _all_names()
    for name, key in names:
        if norm == name:
            return key
    # small typos in the whole term ("aanslag gemeentelijk belasting")
    close = difflib.get_close_matches(norm, [name for name, _ in names], n=1, cutoff=0.85)
    if close:
        return dict(names)[close[0]]
    # the user typed a longer phrase that contains a known term (longest first)
    for name, key in names:
        if len(name) >= 3 and re.search(rf"\b{re.escape(name)}\b", norm):
            return key
    return None


def find_terms_in_text(text: Text) -> List[Text]:
    """All glossary keys mentioned in a longer text, without overlapping matches."""
    norm = _normalise(text)
    first_seen: Dict[Text, int] = {}
    taken: List[Tuple[int, int]] = []
    for name, key in _all_names():
        for match in re.finditer(rf"\b{re.escape(name)}\b", norm):
            span = match.span()
            if any(s <= span[0] and span[1] <= e for s, e in taken):
                continue
            taken.append(span)
            first_seen[key] = min(first_seen.get(key, span[0]), span[0])
    # the specific term already explains what an 'aanslag' is about
    if "aanslag gemeentelijke belastingen" in first_seen:
        first_seen.pop("aanslag", None)
    # explain terms in the order they appear in the letter
    return sorted(first_seen, key=first_seen.get)


def detect_sender(text: Text) -> Optional[Text]:
    norm = _normalise(text)
    if re.search(r"municipal|gemeente|city hall|town hall|nijmegen", norm):
        return "municipality"
    if re.search(r"belastingdienst|tax office|tax authority|tax authorities", norm):
        return "belastingdienst"
    return None


class ActionLookupTerm(Action):
    """Diagram decision 'Term recognized?'."""

    def name(self) -> Text:
        return "action_lookup_term"

    def run(
        self,
        dispatcher: CollectingDispatcher,
        tracker: Tracker,
        domain: Dict[Text, Any],
    ) -> List[Dict[Text, Any]]:
        events: List[Dict[Text, Any]] = []
        message = tracker.latest_message.get("text") or ""

        if not tracker.get_slot("sender"):
            sender = detect_sender(message)
            if sender:
                events.append(SlotSet("sender", sender))

        key = lookup_term(tracker.get_slot("term"))
        if key:
            return events + [
                SlotSet("term_known", True),
                SlotSet("term_explanation", GLOSSARY[key]["explanation"]),
                SlotSet("term_retry", False),
            ]

        attempts = (tracker.get_slot("term_attempts") or 0) + 1
        return events + [
            SlotSet("term_known", False),
            SlotSet("term_attempts", attempts),
            SlotSet("term_retry", True),
            SlotSet("term", None),  # so the flow asks for the term again
        ]


class ActionCheckLetterInMessage(Action):
    """If the user already pasted the letter, use it instead of asking for it."""

    def name(self) -> Text:
        return "action_check_letter_in_message"

    def run(
        self,
        dispatcher: CollectingDispatcher,
        tracker: Tracker,
        domain: Dict[Text, Any],
    ) -> List[Dict[Text, Any]]:
        message = tracker.latest_message.get("text") or ""
        looks_like_letter = len(message) >= 150 or (
            len(message) >= 60 and (AMOUNT_RE.search(message) or find_terms_in_text(message))
        )
        if looks_like_letter and not tracker.get_slot("letter_content"):
            return [SlotSet("letter_content", message)]
        return []


class ActionExplainLetter(Action):
    """Diagram: 'Explains what the letter says, then asks follow-up'."""

    def name(self) -> Text:
        return "action_explain_letter"

    def run(
        self,
        dispatcher: CollectingDispatcher,
        tracker: Tracker,
        domain: Dict[Text, Any],
    ) -> List[Dict[Text, Any]]:
        letter = tracker.get_slot("letter_content") or ""
        latest = tracker.latest_message.get("text") or ""
        # the LLM may shorten a long pasted letter when filling the slot
        if len(latest) > len(letter):
            letter = latest

        terms = find_terms_in_text(letter)
        amounts = list(dict.fromkeys(AMOUNT_RE.findall(letter)))
        dates = list(dict.fromkeys(DATE_RE.findall(letter)))

        if not terms and not amounts:
            text = (
                "I'm sorry, I couldn't find any terms I know in this letter, so I can't "
                "explain it reliably. The organisation that sent it can help you: their "
                "phone number is usually printed on the letter."
            )
            return [SlotSet("letter_explanation", text), SlotSet("letter_content", None)]

        lines = ["Here's what I can tell you about your letter:"]
        for key in terms:
            lines.append(f"• {GLOSSARY[key]['explanation']}")
        if amounts:
            lines.append(f"• Amount(s) mentioned: {', '.join(amounts)}.")
        if dates:
            lines.append(
                f"• Date(s) mentioned: {', '.join(dates)}. One of these is usually the date "
                "of the letter and another the payment deadline."
            )
        lines.append(
            "Please note that I can only explain the terms I recognise. I can't check "
            "whether the amounts are correct."
        )
        return [SlotSet("letter_explanation", "\n".join(lines))]


class ActionCountFailedAttempt(Action):
    """Counts 'could you rephrase?' turns so the bot can refer after 2 fails."""

    def name(self) -> Text:
        return "action_count_failed_attempt"

    def run(
        self,
        dispatcher: CollectingDispatcher,
        tracker: Tracker,
        domain: Dict[Text, Any],
    ) -> List[Dict[Text, Any]]:
        count = (tracker.get_slot("rephrase_count") or 0) + 1
        return [SlotSet("rephrase_count", count)]
